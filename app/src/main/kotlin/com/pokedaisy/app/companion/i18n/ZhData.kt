package com.pokedaisy.app.companion.i18n

/**
 * Chinese names for game data (species / moves / items), keyed by the English name
 * the game's own tables give. [trName] translates one shown name when the language
 * is ZH; a miss stays as it is. [fixRomText] re-decodes a mojibake name from its raw
 * ROM bytes as GBK, for the Chinese-localised ROMs whose text is GBK-based.
 *
 * Names from HI问风's Chinese build of PokeDaisy (GPLv3), re-homed here.
 */
object ZhData {
    /** The Chinese tables are ZH-only: anything else never sees them. */
    fun zhGate(): Boolean = L10n.language == AppLanguage.ZH

    /** One shown game name (species, move or item) in Chinese, or null to show it as it is. */
    fun trName(en: String?): String? {
        if (en == null || !zhGate()) return null
        return SPECIES[en] ?: MOVES[en] ?: ITEMS[en]
    }

    /**
     * A name decoded with a Latin charset that came out mojibake (chars in 0x80..0xFF)
     * gets one more try as GBK from its raw ROM bytes - the Chinese-localised ROMs keep
     * their text in GBK-derived encodings. Anything else stays [decoded].
     */
    fun fixRomText(decoded: String?, raw: ByteArray, off: Int, len: Int): String? {
        try {
            if (decoded == null || !zhGate()) return decoded
            var high = 0
            for (c in decoded) if (c.code in 0x80..0xFF) high++
            if (high == 0) return decoded
            val gbk = String(raw, off, len, charset("GBK"))
            for (c in gbk) if (c.code in 0x4E00..0x9FFF) return gbk
        } catch (_: Throwable) {
        }
        return decoded
    }

